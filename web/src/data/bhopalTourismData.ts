export function getTouristPlaceBySlug(slug: string): TouristPlace | undefined {
  const normalized = slug.trim().toLowerCase();
  return BHOPAL_TOURIST_DESTINATIONS.find(
    (p) =>
      p.slug.toLowerCase() === normalized ||
      p.id.toLowerCase() === normalized ||
      p.aliases?.some((a) => a.toLowerCase().replace(/\s+/g, '-') === normalized),
  );
}

export function getRelatedTouristPlaces(currentId: string, limit = 3): TouristPlace[] {
  const current = BHOPAL_TOURIST_DESTINATIONS.find((p) => p.id === currentId);
  if (!current) return BHOPAL_TOURIST_DESTINATIONS.slice(0, limit);

  return BHOPAL_TOURIST_DESTINATIONS.filter(
    (p) =>
      p.id !== currentId &&
      (p.category === current.category ||
        p.categories.some((c) => current.categories.includes(c)) ||
        current.nearbyPlaces.some((n) => p.name.toLowerCase().includes(n.toLowerCase()))),
  ).slice(0, limit);
}

